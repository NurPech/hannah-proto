#!/usr/bin/env node
// Generates src/compat_versions.ts from the current proto schema — the
// per-method compat_version map the TS compat interceptor
// (interceptor/compat_interceptor.ts) needs at runtime.
//
// ts-proto (buf.gen.ts.yaml) runs without `outputSchema`, so the generated
// message types carry no descriptor/options data at runtime — unlike
// Python/Go, there's no reflection API to read compat_version off a
// generated TS type directly. This script works around that by parsing
// buf's own JSON descriptor output instead, at build time, and writing a
// plain static map — same spirit as the existing `echo ... > src/version.ts`
// line just above where this is called from generate.sh.
//
// NOT YET VERIFIED end-to-end (no build environment available to run this
// in while drafting it). In particular: whether `buf build --format=json`
// resolves the `compat_version` extension (options.proto) to the bracketed
// key form assumed below (`"[hannah.compat_version]"`) needs confirming
// against real output before this is trusted — that's the standard
// protobuf-JSON convention for extension fields, but hasn't been checked
// against this specific buf version's actual output here.

const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const REPO_ROOT = path.resolve(__dirname, "..", "..");
const BUF_BIN = process.env.BUF_BIN || "buf";
const EXTENSION_KEY = "[hannah.compat_version]";
const DEFAULT_COMPAT_VERSION = 1;

function loadDescriptorSet() {
  const tmpFile = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "hannah-proto-descriptor-")), "descriptor.json");
  execFileSync(BUF_BIN, ["build", "--output", tmpFile], { cwd: REPO_ROOT });
  const raw = fs.readFileSync(tmpFile, "utf8");
  return JSON.parse(raw);
}

// message full_name (e.g. "hannah.SetGroupSatellitesRequest") -> compat_version,
// only for messages that explicitly set the option (absent = implicit 1,
// per options.proto's documented convention — don't backfill entries here).
function messageCompatVersions(descriptorSet) {
  const versions = {};
  for (const file of descriptorSet.file ?? []) {
    const pkg = file.package ?? "";
    const walk = (messages, prefix) => {
      for (const msg of messages ?? []) {
        const fullName = `${prefix}${msg.name}`;
        const v = msg.options?.[EXTENSION_KEY];
        if (typeof v === "number") {
          versions[fullName] = v;
        }
        walk(msg.nestedType, `${fullName}.`);
      }
    };
    walk(file.messageType, pkg ? `${pkg}.` : "");
  }
  return versions;
}

// bare RPC method name (e.g. "SubmitText") -> max(compat_version of its
// request type, compat_version of its response type). Bare name, not the
// full "/pkg.Service/Method" path, because that's what the interceptor has
// available (options.method_definition.path split on "/").
function requiredCompatVersions(descriptorSet, msgVersions) {
  const required = {};
  for (const file of descriptorSet.file ?? []) {
    for (const service of file.service ?? []) {
      for (const method of service.method ?? []) {
        const inputType = method.inputType.replace(/^\./, "");
        const outputType = method.outputType.replace(/^\./, "");
        const v = Math.max(
          msgVersions[inputType] ?? DEFAULT_COMPAT_VERSION,
          msgVersions[outputType] ?? DEFAULT_COMPAT_VERSION,
        );
        required[method.name] = v;
      }
    }
  }
  return required;
}

const descriptorSet = loadDescriptorSet();
const msgVersions = messageCompatVersions(descriptorSet);
const required = requiredCompatVersions(descriptorSet, msgVersions);

const out = [
  "// Generated by scripts/gen-compat-versions.js — do not edit by hand.",
  `export const DEFAULT_COMPAT_VERSION = ${DEFAULT_COMPAT_VERSION};`,
  `export const REQUIRED_COMPAT_VERSIONS: Record<string, number> = ${JSON.stringify(required, null, 2)};`,
  "",
].join("\n");

fs.writeFileSync(path.join(REPO_ROOT, "npm", "src", "compat_versions.ts"), out);
console.log(`compat_versions.ts written (${Object.keys(required).length} methods).`);
